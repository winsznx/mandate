#!/usr/bin/env node
/**
 * Bundle the published artifacts the marketplace reads into a generated module.
 *
 * `apps/web/src/marketplace/repo-files.ts` used to read `artifacts/` off disk
 * with `node:fs`. That works under Node but not on Cloudflare Workers, where
 * there is no repository on disk. This script snapshots exactly the files the
 * inventory reads into `published-snapshot.generated.ts`, so the same data is
 * available at request time in either runtime, with no network call.
 *
 * The snapshot is regenerated from the artifacts and checked in CI, so it
 * cannot drift from them and cannot be edited without the artifacts changing.
 *
 * Usage:  node scripts/emit-published-snapshot.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(repoRoot, "apps/web/src/marketplace/published-snapshot.generated.ts");

const AGENTS_DIR = "artifacts/agents";
const EVIDENCE_DIR = "artifacts/evidence";
const DEPLOYMENT_FILE = "contracts/deployments/97.json";

/** relative path -> parsed JSON. Only the files the inventory actually reads. */
const files = {};
/** relative dir -> sorted entry names, so `listJsonFiles` / `listDirectories` still work. */
const dirs = {};

function readJson(relativePath) {
  return JSON.parse(readFileSync(join(repoRoot, relativePath), "utf8"));
}

// Agent cards.
const agentFiles = readdirSync(join(repoRoot, AGENTS_DIR))
  .filter((name) => name.endsWith(".json"))
  .sort();
dirs[AGENTS_DIR] = agentFiles;
for (const name of agentFiles) {
  const rel = `${AGENTS_DIR}/${name}`;
  files[rel] = readJson(rel);
}

// Evidence run manifests.
const evidenceDirs = readdirSync(join(repoRoot, EVIDENCE_DIR), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
dirs[EVIDENCE_DIR] = evidenceDirs;
for (const name of evidenceDirs) {
  const rel = `${EVIDENCE_DIR}/${name}/proof-manifest.json`;
  try {
    files[rel] = readJson(rel);
  } catch {
    // A run directory without a manifest is skipped by the inventory too.
  }
}

// Registry deployment record.
files[DEPLOYMENT_FILE] = readJson(DEPLOYMENT_FILE);

const banner =
  "// GENERATED by scripts/emit-published-snapshot.mjs — do not edit.\n" +
  "// Run `node scripts/emit-published-snapshot.mjs` after changing anything under\n" +
  "// artifacts/agents, artifacts/evidence, or contracts/deployments/97.json.\n\n";

const body =
  `export const SNAPSHOT_FILES: Readonly<Record<string, unknown>> = ${JSON.stringify(files, null, 2)} as const;\n\n` +
  `export const SNAPSHOT_DIRS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(dirs, null, 2)} as const;\n`;

writeFileSync(out, banner + body, "utf8");
console.log(
  `Wrote ${out}\n  ${agentFiles.length} agent cards, ${evidenceDirs.length} evidence dirs, 1 deployment record.`,
);
